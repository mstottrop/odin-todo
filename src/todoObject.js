class todoInstance {
  constructor(title, description, dueDate, priority, notes, checklist, images) {
    this.title = title;
    this.description = description;
    this.dueDate = dueDate;
    this.priority = priority;
    this.notes = notes;
    this.checklist = checklist;
    this.images = images;
  }
}

